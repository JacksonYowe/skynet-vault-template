#!/usr/bin/env python3
"""Skynet LLM-wiki tool. Stdlib only.

  vault.py index [-q]      rebuild index.md from wiki/ frontmatter (`summary:`)
  vault.py find WORDS...   rank wiki pages by keyword hits (names + summaries weigh most)
  vault.py lint            missing summaries, missing pages, orphans, stale pages,
                           oversized pages, raw files no page cites, raw/inbox backlog
  vault.py log OP TITLE    append "## [YYYY-MM-DD] OP | TITLE" to log.md
"""
import os, re, sys, time, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIKI, RAW, ARCH = (os.path.join(ROOT, d) for d in ("wiki", "raw", "archive"))
TYPES = ["overview", "subject", "assessment", "topic", "source", "method", "reference",
         "project", "app", "system", "activity", "person", "answer"]
BIG = 12_000
STALE_DAYS = 60
FM = re.compile(r"^---\n(.*?)\n---\n", re.S)
LINK = re.compile(r"\[\[([^\]|#\\]+)")


def meta(text):
    m = FM.match(text)
    out = {}
    for line in (m.group(1).splitlines() if m else []):
        k, _, v = line.partition(":")
        if v and not line.startswith(" "):
            out[k.strip()] = v.strip()
    return out


def pages():
    for f in sorted(os.listdir(WIKI)):
        if f.endswith(".md"):
            p = os.path.join(WIKI, f)
            yield f[:-3], p, open(p, encoding="utf-8", errors="replace").read()


def build_index(quiet=False):
    groups = {}
    for name, p, text in pages():
        m = meta(text)
        flags = [f"{k}={m[k]}" for k in ("status", "due") if m.get(k)]
        size = len(text.encode())
        if size > BIG:
            flags.append(f"{size // 1000}kB")
        line = f"- {name}: {m.get('summary', '~NO SUMMARY')}" + (f" [{' '.join(flags)}]" if flags else "")
        groups.setdefault(m.get("type", "untyped"), []).append(line)
    n = sum(map(len, groups.values()))
    out = ["---", "type: index", f"updated: {datetime.date.today()}", "---",
           f"# index: {n} wiki pages (generated by tools/vault.py; do not hand-edit)",
           "Every page is wiki/<name>.md. Line = name: summary [status/due/size]. "
           "Read this, then open only the pages you need.", ""]
    for t in sorted(groups, key=lambda t: TYPES.index(t) if t in TYPES else 99):
        out.append(f"## {t}")
        out += groups[t]
    # raw layer: counts only
    raw = {}
    for dp, dn, fn in os.walk(RAW):
        dn[:] = sorted(dn)
        files = [f for f in fn if not f.startswith(".")]
        if files:
            key = "/".join(os.path.relpath(dp, RAW).split(os.sep)[:2])
            raw[key] = raw.get(key, 0) + len(files)
    out.append("## raw (immutable sources; cite by path, never edit)")
    out += [f"- raw/{k}: {v} files" for k, v in sorted(raw.items())] or ["- (empty)"]
    # archive: one line per folder
    out.append("## archive (history only)")
    for d in sorted(os.listdir(ARCH)):
        dp = os.path.join(ARCH, d)
        if not os.path.isdir(dp):
            continue
        about, count = "", 0
        for sub, _, fn in os.walk(dp):
            for f in sorted(fn):
                if f.endswith(".md"):
                    count += 1
                    about = about or meta(open(os.path.join(sub, f), errors="replace").read()).get("archive-summary", "")
        out.append(f"- archive/{d} ({count} notes){': ' + about if about else ''}")
    with open(os.path.join(ROOT, "index.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    if not quiet:
        print(f"index.md: {n} pages")


def find(words):
    words = [w.lower() for w in words]
    scored = []
    for name, p, text in pages():
        m = meta(text)
        head = (name + " " + m.get("summary", "")).lower()
        body = text.lower()
        score = sum(10 * head.count(w) + min(body.count(w), 10) for w in words)
        if score:
            scored.append((score, name, m.get("summary", "")))
    for score, name, s in sorted(scored, reverse=True)[:10]:
        print(f"{score:>4}  {name}: {s}")


def lint():
    names, inbound, texts = set(), {}, {}
    for name, p, text in pages():
        names.add(name)
        texts[name] = (p, text)
    all_files = set()
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = [d for d in dn if d not in {".git", ".obsidian"}]
        for f in fn:
            all_files.add(f)
            all_files.add(os.path.splitext(f)[0])
            all_files.add(os.path.relpath(os.path.join(dp, f), ROOT))
    missing, report = {}, []
    cited = " ".join(t for _, t in texts.values())
    now = time.time()
    for name, (p, text) in texts.items():
        m = meta(text)
        issues = []
        if not m.get("summary"):
            issues.append("no summary")
        if len(text.encode()) > BIG:
            issues.append(f"{len(text.encode()) // 1000}kB, split or fold history")
        if m.get("type") in ("overview", "project") and now - os.path.getmtime(p) > STALE_DAYS * 86400:
            issues.append(f"not updated in {STALE_DAYS}+ days, check claims")
        for target in {l.strip() for l in LINK.findall(text)}:
            base = os.path.basename(target)
            if base in names:
                inbound.setdefault(base, set()).add(name)
            elif target not in all_files and base not in all_files:
                missing.setdefault(base, set()).add(name)
        if issues:
            report.append(f"  {name}: " + "; ".join(issues))
    orphans = sorted(n for n in names if not (inbound.get(n, set()) - {n})
                     and meta(texts[n][1]).get("type") != "overview")  # overviews are roots
    raw_files = []
    for dp, dn, fn in os.walk(RAW):
        for f in fn:
            if not f.startswith(".") and f not in cited and os.path.splitext(f)[0] not in cited:
                raw_files.append(os.path.relpath(os.path.join(dp, f), ROOT))
    os.makedirs(os.path.join(RAW, "inbox"), exist_ok=True)
    inbox = [f for f in os.listdir(os.path.join(RAW, "inbox")) if not f.startswith(".")]
    print("PAGES" if report else "PAGES: ok", *report, sep="\n")
    print(f"MISSING PAGES (linked but absent; create or unlink): {len(missing)}")
    for k, v in sorted(missing.items()):
        print(f"  [[{k}]] <- {', '.join(sorted(v))[:120]}")
    print(f"ORPHANS (no inbound links; link from a subject/overview page): {len(orphans)}")
    if orphans:
        print("  " + ", ".join(orphans))
    print(f"UNCITED RAW (no wiki page mentions them; ingest or ignore): {len(raw_files)}")
    for r in sorted(raw_files)[:15]:
        print("  " + r)
    print(f"INBOX (awaiting ingest): {len(inbox)}" + ("\n  " + ", ".join(inbox) if inbox else ""))


def log(op, title):
    with open(os.path.join(ROOT, "log.md"), "a", encoding="utf-8") as fh:
        fh.write(f"## [{datetime.date.today()}] {op} | {title}\n")


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a or a[0] == "index":
        build_index("-q" in a)
    elif a[0] == "find" and len(a) > 1:
        find(a[1:])
    elif a[0] == "lint":
        lint()
    elif a[0] == "log" and len(a) > 2:
        log(a[1], " ".join(a[2:]))
    else:
        print(__doc__)
